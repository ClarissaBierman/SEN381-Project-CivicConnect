-- V2: bring the V1 schema in line with the current JPA entities.
--  - active flags on client and employee (deactivate, never delete)
--  - client.updated_at
--  - request.location NOT NULL, closed_at rule, reference number sequence
--  - request_handler gets its own key + "one active handler" index (FR-008)
--  - new handler_category (FR-005) and comment (FR-010) tables
--  - audit_entry becomes a row-level change log written by a trigger (DEC-007)
--  - comment and audit_entry are append-only
-- Never edit this file after it has run anywhere - add V3 instead (DEC-008).
